#!/usr/bin/env python3
"""Q017 endpoint term sets from config/q017_endpoint_roots_v1.json by HPO is_a closure (plans/q017_redteam.md MUST 4,
spec section 5). Ontology only (data/db_setup/ontologies/hp.obo): no gene, disease or annotation data is read.
Writes config/q017_endpoint_map_v1.json (term IDs only). No per-term hand edits: every change goes through a root.

  Y_core = closure(Y_core_include_roots) - closure(Y_core_exclude_roots) - obsolete
           - terms whose label contains any label_exclude_words substring (lowercase)
  Y_exc  = closure(Y_exc_roots) - closure(Y_exc_minus_roots) - closure(Y_core_include_roots) - obsolete

  python harness/q017_endpoint_map.py            build + print set sizes
  python harness/q017_endpoint_map.py --sample 60 [--seed 17]   also print a random sample of Y_core names
  python harness/q017_endpoint_map.py --dump     also print every Y_core name and every label-word casualty
"""
import argparse
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from db_endpoint_map import O, ROOT, closure, parse  # noqa: E402

CFG = ROOT / "config/q017_endpoint_roots_v1.json"
OUT = ROOT / "config/q017_endpoint_map_v1.json"


def obsolete(path):
    out, cur = set(), None
    for line in open(path):
        if line.startswith("id: "):
            cur = line[4:].strip()
        elif line.startswith("is_obsolete: true") and cur:
            out.add(cur)
    return out


def build():
    R = json.loads(CFG.read_text())
    assert R["relations"] == ["is_a"]
    ch, nm = parse(O / "hp.obo", tuple(R["relations"]))
    obs = obsolete(O / "hp.obo")
    for k in ("Y_core_include_roots", "Y_core_exclude_roots", "Y_exc_roots", "Y_exc_minus_roots"):
        bad = [t for t in R[k] if t not in nm or t in obs]
        assert not bad, f"{k}: unresolved or obsolete {bad}"
        assert len(set(R[k])) == len(R[k]), f"{k}: duplicate root"
    words = [w.lower() for w in R["label_exclude_words"]]
    inc = closure(R["Y_core_include_roots"], ch) - obs
    exc = closure(R["Y_core_exclude_roots"], ch)
    by_root = inc & exc
    by_word = {t for t in inc - exc if any(w in nm[t].lower() for w in words)}
    y = inc - exc - by_word
    yexc = closure(R["Y_exc_roots"], ch) - closure(R["Y_exc_minus_roots"], ch) - inc - obs
    assert not (y & yexc)
    return R, nm, y, yexc, by_root, by_word, inc


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sample", type=int, default=0)
    ap.add_argument("--seed", type=int, default=17)
    ap.add_argument("--dump", action="store_true")
    a = ap.parse_args()
    R, nm, y, yexc, by_root, by_word, inc = build()
    out = {"note": "Generated by harness/q017_endpoint_map.py from config/q017_endpoint_roots_v1.json; term IDs only.",
           "hp_data_version": next((l.split(": ", 1)[1].strip() for l in open(O / "hp.obo")
                                    if l.startswith("data-version: ")), None),
           "Y_core_terms": sorted(y), "Y_exc_terms": sorted(yexc),
           "Y_core_removed_by_exclude_roots": sorted(by_root), "Y_core_removed_by_label_words": sorted(by_word)}
    OUT.write_text(json.dumps(out, indent=0))
    print({k: (len(v) if isinstance(v, list) else v) for k, v in out.items() if k != "note"},
          "include_closure", len(inc))
    if a.sample:
        for t in random.Random(a.seed).sample(sorted(y), min(a.sample, len(y))):
            print("SAMPLE", t, nm[t])
    if a.dump:
        for t in sorted(y, key=nm.get):
            print("Y", t, nm[t])
        for t in sorted(by_word, key=nm.get):
            print("WORD", t, nm[t])
        for t in sorted(by_root, key=nm.get):
            print("ROOT", t, nm[t])
    return 0


if __name__ == "__main__":
    sys.exit(main())
